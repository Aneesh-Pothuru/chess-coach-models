#!/usr/bin/env bash
# Run a headless Claude Code session the way a routine would: no effort override,
# no inherited session, memory, MCP, hooks or GitHub credentials from the parent.
# Usage: claude-clean.sh <cwd> [claude args...]   (prompt on stdin)
set -euo pipefail
cwd="$1"; shift
drop=(CLAUDE_EFFORT MAX_THINKING_TOKENS CLAUDE_CODE_SESSION_ID CLAUDE_CODE_REMOTE_SESSION_ID CLAUDE_CODE_PROJECTS_SESSION
  CLAUDE_CODE_COORDINATOR_EXTRA_TOOLS CLAUDE_COWORK_MEMORY_PATH_OVERRIDE CLAUDE_MEMORY_STORES CLAUDE_CODE_SKILL_PROPOSALS
  CLAUDE_CODE_TERMINAL_MCP_TOOLS CLAUDE_CODE_MESSAGING_SOCKET CLAUDE_CODE_MESSAGING_TOKEN CLAUDE_ADDITIONAL_DIRECTORIES
  CLAUDE_CODE_ADDITIONAL_DIRECTORIES_CLAUDE_MD CLAUDE_CODE_ARTIFACT_ASSETS CLAUDE_CODE_CHILD_SESSION CLAUDE_AFTER_LAST_COMPACT
  CLAUDE_AUTOCOMPACT_PCT_OVERRIDE CLAUDE_CODE_AUTO_COMPACT_WINDOW CLAUDE_CODE_SYNC_SKILLS CLAUDE_CODE_SYNC_PLUGINS
  CLAUDE_CODE_SYNC_SESSION_REFS CLAUDE_CODE_ENABLE_REMOTE_RECAP CLAUDE_CODE_SILENT_TURN_REMINDER CLAUDE_CODE_BG_TASKS_REPORT_RUNNING
  CLAUDE_AUTO_BACKGROUND_TASKS CLAUDE_CODE_DIAGNOSTICS_FILE CLAUDE_CODE_DEBUG CLAUDE_CODE_MAX_SUBAGENT_SPAWN_DEPTH
  CCR_OPUS_REMINDER_HOOK_BODY CCR_REPLY_STOP_HOOK_HOLDING_TOOL CCR_REPLY_STOP_HOOK_LOCAL_CAP CCR_REPLY_STOP_HOOK_REASON
  CCR_REPLY_STOP_HOOK_TERMINAL_TOOLS CCR_HEARTH_STATUS_NUDGE_SECONDS CCR_PRELOAD_CLAUDE
  CLAUDE_CODE_ARTIFACT_DB CLAUDE_CODE_ARTIFACT_MULTI_FILE CLAUDE_CODE_ARTIFACT_TYPES CLAUDE_CODE_ARTIFACT_TYPE_CATALOG
  CLAUDE_CODE_ARTIFACT_TYPE_CLOUD_CREATE CLAUDE_CODE_SESSION_ATTENDED CLAUDE_CODE_ENABLE_PROMPT_SUGGESTION
  CLAUDE_CODE_INCLUDE_PARTIAL_MESSAGES
  GH_TOKEN GITHUB_TOKEN CLOUDSDK_AUTH_ACCESS_TOKEN AWS_ACCESS_KEY_ID AWS_SECRET_ACCESS_KEY DOCUMENTS_MCP_SCRATCH_ROOT)
args=()
for v in "${drop[@]}"; do args+=(-u "$v"); done
cd "$cwd"
exec env "${args[@]}" CLAUDE_CODE_ENTRYPOINT=sdk-cli claude -p --strict-mcp-config --mcp-config '{"mcpServers":{}}' --setting-sources project,local "$@"
