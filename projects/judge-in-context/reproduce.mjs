#!/usr/bin/env node
// Reproduces the judge-in-context numbers in the lab, two ways.
//
// Recomputed: the judge's preferences (tally.mjs over the judge rounds the
// records keep), checked against the table the records' judge-results.md
// published.
//
// Rerun: flips.mjs on the engine evidence the lab rebuilt on the pinned app
// (build-evidence.mjs, phone profile), its counts set beside the counts the
// records' flips.json holds.
//
//   bridge/run.sh projects/judge-in-context/reproduce.mjs [--no-rerun]
//
// The rerun's flips (which name games) stay in private/judge-in-context/
// reproduce/; results/reproduction.{md,json} hold aggregates only.

import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CHESS_DIR, LAB_DIR, privateDir, projectDir, records, resultsDir } from '../../bridge/lib/chess.mjs';
import { tally } from './tally.mjs';

const FLOW = 'judge-in-context';
const git = (dir, ...args) => execFileSync('git', ['-C', dir, ...args], { encoding: 'utf8' }).trim();
const read = path => JSON.parse(readFileSync(path, 'utf8'));

/** The run columns of the published result table: {shipped: [r1, r2], proposed: [...], unsure: [...]}, and the agreement line. */
function published(path) {
  const md = readFileSync(path, 'utf8');
  const row = label => {
    const line = md.split('\n').find(l => l.startsWith(`| ${label} |`));
    if (!line) throw new Error(`${path}: no "${label}" row`);
    return line.split('|').slice(2, -1).map(s => Number(s.trim()));
  };
  const same = md.match(/same answer on (\d+) of (\d+) moves/);
  return {
    shipped: row('shipped verdict preferred'),
    proposed: row('proposed verdict preferred'),
    unsure: row('unsure'),
    identical: same ? Number(same[1]) : null,
  };
}

/** The counts a flips.json carries that a rerun can be held to. */
function counts(flips) {
  const c = flips.counts;
  return {
    evidenceVersion: flips.inputs.evidenceVersion,
    games: c.games,
    records: c.records,
    exactScorePlies: c.exactScorePlies,
    gradedPlies: c.gradedPlies,
    gradedByRole: c.gradedByRole,
    flips: c.flips,
    flipShare: c.flipShare,
    flipsByRole: c.flipsByRole,
    assertionPassed: flips.assertion.passed,
  };
}

function main() {
  const recorded = join(records(), 'evals', FLOW);

  const t = tally(join(recorded, 'judge'));
  const pub = published(join(recorded, 'judge-results.md'));
  const runs = Object.keys(t.runs);
  const matches = ['shipped', 'proposed', 'unsure'].every(w => runs.every((r, i) => t.runs[r][w] === pub[w][i])) && t.identical === pub.identical;

  const out = join(privateDir(FLOW), 'reproduce');
  if (!process.argv.includes('--no-rerun')) {
    console.error('[reproduce] flips on the rebuilt phone evidence');
    mkdirSync(out, { recursive: true });
    execFileSync(join(LAB_DIR, 'bridge', 'run.sh'), [join(projectDir(FLOW), 'flips.mjs'), '--out', out], {
      cwd: LAB_DIR, stdio: ['ignore', 'ignore', 'inherit'],
    });
  }
  if (!existsSync(join(out, 'flips.json'))) throw new Error(`no rerun in ${out}: run without --no-rerun`);

  const report = {
    eval: 'judge-in-context reproduction',
    chess: { pinned_commit: git(CHESS_DIR, 'rev-parse', 'HEAD'), records_commit: git(records(), 'rev-parse', 'HEAD') },
    judge: { matchesPublished: matches, tally: t, published: pub },
    flips: { recorded: counts(read(join(recorded, 'flips.json'))), rerun: counts(read(join(out, 'flips.json'))) },
  };
  writeFileSync(join(resultsDir(FLOW), 'reproduction.json'), JSON.stringify(report, null, 2) + '\n');
  writeFileSync(join(resultsDir(FLOW), 'reproduction.md'), render(report));
  console.log(render(report));
}

function render(report) {
  const { tally: t } = report.judge;
  const runs = Object.keys(t.runs);
  const a = report.flips.recorded, b = report.flips.rerun;
  const share = x => `${(100 * x).toFixed(1)}%`;
  const L = [
    '# Judging in context: the numbers reproduced in the lab',
    '',
    `Generated by \`projects/judge-in-context/reproduce.mjs\` on app commit \`${report.chess.pinned_commit.slice(0, 7)}\`, reading the records at \`${report.chess.records_commit.slice(0, 7)}\`.`,
    '',
    '## The judge, recomputed from the records',
    '',
    `${report.judge.matchesPublished ? 'Every number of the published table is recomputed exactly' : 'The recomputed table differs from the published one'} from the judge's answers and each run's order key.`,
    '',
    `| | ${runs.map(r => `run ${r.slice(1)}`).join(' | ')} |`,
    `|---|${runs.map(() => '---').join('|')}|`,
    `| shipped verdict preferred | ${runs.map(r => t.runs[r].shipped).join(' | ')} |`,
    `| proposed verdict preferred | ${runs.map(r => t.runs[r].proposed).join(' | ')} |`,
    `| unsure | ${runs.map(r => t.runs[r].unsure).join(' | ')} |`,
    '',
    `The two runs agree on ${t.identical} of ${t.moves} moves.`,
    '',
    '## The flips, rerun on the pinned app',
    '',
    '| | recorded | rerun |',
    '|---|---|---|',
    `| evidence | ${a.evidenceVersion} | ${b.evidenceVersion} |`,
    `| games | ${a.games} | ${b.games} |`,
    `| plies with exact scores | ${a.exactScorePlies} | ${b.exactScorePlies} |`,
    `| graded plies | ${a.gradedPlies} | ${b.gradedPlies} |`,
    `| flips | ${a.flips} (${share(a.flipShare)}) | ${b.flips} (${share(b.flipShare)}) |`,
    `| the player's flips | ${a.flipsByRole.player} of ${a.gradedByRole.player} | ${b.flipsByRole.player} of ${b.gradedByRole.player} |`,
    `| the opponents' flips | ${a.flipsByRole.opponent} of ${a.gradedByRole.opponent} | ${b.flipsByRole.opponent} of ${b.gradedByRole.opponent} |`,
    `| the judge's copy matches the real judge | ${a.assertionPassed ? 'yes' : 'no'} | ${b.assertionPassed ? 'yes' : 'no'} |`,
    '',
  ];
  return L.join('\n');
}

main();
